"""V43.15: public VSDX orthogonal intent, not Microsoft Visio Desktop fidelity.

Fixtures are generated by the OpenVisio exporter, then stripped of its private
JSON payload to exercise the public OPC page importer only.
Author: Abdelhalim Talbi.
"""
import tempfile
import unittest
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile

from openvisio.vsdx import export_vsdx, import_vsdx
from openvisio.vsdx_external import V


def sample(*, routing='orthogonal', parallel=False):
    edges = [{'id': 'fabric-A', 'from': 'switch', 'to': 'array',
              'routing': routing, 'protocol': 'FC', 'label': 'FC A',
              'fabric': 'A', 'source_port': 'fc0', 'target_port': 'fa0'}]
    if parallel:
        edges.append({'id': 'fabric-B', 'from': 'switch', 'to': 'array',
                      'routing': routing, 'protocol': 'FC', 'label': 'FC B',
                      'fabric': 'B', 'source_port': 'fc1', 'target_port': 'fa1'})
    return {'nodes': [
        {'id': 'switch', 'x': 80, 'y': 100, 'shape': 'san-switch', 'label': 'G720'},
        {'id': 'array', 'x': 500, 'y': 300, 'shape': 'storage', 'label': 'PowerMax'}],
        'edges': edges}


def external_fixture(path, document, *, mutate=None):
    embedded = path.with_name('embedded.vsdx')
    export_vsdx(embedded, document)
    with ZipFile(embedded) as source:
        parts = {name: source.read(name) for name in source.namelist()
                 if not name.startswith('openvisio/')}
    if mutate is not None:
        page = ET.fromstring(parts['visio/pages/page1.xml'])
        mutate(page)
        parts['visio/pages/page1.xml'] = ET.tostring(page, encoding='utf-8')
    with ZipFile(path, 'w') as target:
        for name, payload in parts.items():
            target.writestr(name, payload)


def first_connector(page):
    for shape in page.findall(f'.//{{{V}}}Shape'):
        if any(cell.get('N') == 'OneD' for cell in shape.findall(f'./{{{V}}}Cell')):
            return shape
    raise AssertionError('connector missing')


class ExternalOrthogonalRouteIntent(unittest.TestCase):
    def test_public_orthogonal_route_is_recognized_and_labeled_approximate(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / 'external.vsdx'
            external_fixture(path, sample())
            imported = import_vsdx(path)
            self.assertEqual(imported['edges'][0]['routing'], 'orthogonal')
            self.assertEqual(imported['metadata']['orthogonal_connector_routes_approximated'], 1)
            self.assertIn('connector-waypoints', imported['metadata']['limitations'])
            self.assertIn('not preserved', imported['metadata']['fidelity_warnings'][0])

    def test_straight_route_does_not_acquire_false_orthogonal_preference(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / 'external.vsdx'
            external_fixture(path, sample(routing='straight'))
            imported = import_vsdx(path)
            self.assertNotIn('routing', imported['edges'][0])
            self.assertEqual(imported['metadata']['orthogonal_connector_routes_approximated'], 0)

    def test_two_parallel_fc_routes_remain_distinct_and_orthogonal(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / 'external.vsdx'
            external_fixture(path, sample(parallel=True))
            imported = import_vsdx(path)
            self.assertEqual(len(imported['edges']), 2)
            self.assertEqual({e['label'] for e in imported['edges']}, {'FC A', 'FC B'})
            self.assertEqual({e['routing'] for e in imported['edges']}, {'orthogonal'})
            self.assertEqual(imported['metadata']['orthogonal_connector_routes_approximated'], 2)

    def test_diagonal_geometry_is_not_misclassified_as_orthogonal(self):
        def diagonal(page):
            shape = first_connector(page)
            rows = shape.find(f'./{{{V}}}Section').findall(f'./{{{V}}}Row')
            # Keep begin/end positions unchanged, but make one segment
            # diagonally non-orthogonal in the Visio page coordinate system.
            for cell in rows[1].findall(f'./{{{V}}}Cell'):
                if cell.get('N') == 'Y':
                    cell.set('V', '0.25')
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / 'external.vsdx'
            external_fixture(path, sample(), mutate=diagonal)
            imported = import_vsdx(path)
            self.assertNotIn('routing', imported['edges'][0])
            self.assertEqual(imported['metadata']['orthogonal_connector_routes_approximated'], 0)

    def test_unsupported_visio_formula_rows_do_not_invent_route(self):
        def formula(page):
            shape = first_connector(page)
            rows = shape.find(f'./{{{V}}}Section').findall(f'./{{{V}}}Row')
            rows[1].set('T', 'ArcTo')
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / 'external.vsdx'
            external_fixture(path, sample(), mutate=formula)
            imported = import_vsdx(path)
            self.assertNotIn('routing', imported['edges'][0])

    def test_formula_driven_visio_route_is_not_assumed_static(self):
        def formula(page):
            shape = first_connector(page)
            rows = shape.find(f'./{{{V}}}Section').findall(f'./{{{V}}}Row')
            for cell in rows[1].findall(f'./{{{V}}}Cell'):
                if cell.get('N') == 'X':
                    cell.set('F', 'GUARD(1.25 in)')
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / 'external.vsdx'
            external_fixture(path, sample(), mutate=formula)
            imported = import_vsdx(path)
            self.assertNotIn('routing', imported['edges'][0])

    def test_reexport_keeps_imported_orthogonal_preference_in_private_roundtrip(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / 'external.vsdx'
            external_fixture(path, sample())
            imported = import_vsdx(path)
            reexported = Path(tmp) / 'reexport.vsdx'
            export_vsdx(reexported, imported)
            self.assertEqual(import_vsdx(reexported), imported)


if __name__ == '__main__':
    unittest.main()
